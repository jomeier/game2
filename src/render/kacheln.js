/** Reads a two-bit field into one value per pixel: the index into the material
 * ramp, 0 light through 3 dark. Two pixels live in one hex character.
 */
export function muster(name) {
  const feld = MUSTER[name];
  if (!feld) throw new Error('no baked pattern for ' + name);
  const pixel = new Uint8Array(feld.w * feld.h);
  for (let i = 0; i < pixel.length; i += 1) {
    const paket = parseInt(feld.zeichen[i >> 1], 16);
    pixel[i] = (paket >> ((1 - (i & 1)) * 2)) & 3;
  }
  return { w: feld.w, h: feld.h, pixel };
}
