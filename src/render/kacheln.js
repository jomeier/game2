/** Decodes the tone field: one value per pixel, the index into the ramp. */
export function muster(name) {
  const feld = MUSTER[name];
  if (!feld) throw new Error('no baked pattern for ' + name);
  const pixel = new Uint8Array(feld.w * feld.h);
  for (let i = 0; i < pixel.length; i += 1) {
    const paar = parseInt(feld.toene[i >> 1], 16);
    pixel[i] = (paar >> ((1 - (i & 1)) * 2)) & 3;
  }
  return { w: feld.w, h: feld.h, pixel };
}

/** Decodes the light mask of a front: 1 where the sheet held a warm window. */
export function lichtFeld(name) {
  const feld = MUSTER[name];
  if (!feld || !feld.licht) throw new Error('no light mask for ' + name);
  const pixel = new Uint8Array(feld.w * feld.h);
  for (let i = 0; i < pixel.length; i += 1) {
    const vier = parseInt(feld.licht[i >> 2], 16);
    pixel[i] = (vier >> (3 - (i & 3))) & 1;
  }
  return pixel;
}
